#某大学有 n 个职员，编号为 1 ~ N。他们之间有从属关系，也就是说他们的关系就像一棵以校长为根的树，
#父结点就是子结点的直接上司。现在有个周年庆宴会，宴会每邀请来一个职员都会增加一定的快乐指数 a_i，
#但是，如果某个职员的直接上司来参加舞会了，那么这个职员就无论如何也不肯来参加舞会了

def max_happiness(n, happiness, tree):
    # 初始化 dp 数组
    dp = [[0, 0] for _ in range(n + 1)]
    
    # 深度优先搜索（DFS）函数
    def dfs(u, parent):
        dp[u][0] = 0  # 当前节点不参加舞会
        dp[u][1] = happiness[u]  # 当前节点参加舞会，增加其快乐指数
        
        for v in tree[u]:
            if v == parent:
                continue  # 跳过父节点
            dfs(v, u)  # 递归处理子节点
            
            # 状态转移
            dp[u][0] += max(dp[v][0], dp[v][1])  # 当前节点不参加，子节点可选参加或不参加
            dp[u][1] += dp[v][0]  # 当前节点参加，子节点不能参加
    
    # 从根节点（校长，编号为1）开始进行DFS
    dfs(1, -1)
    
    # 最终结果是根节点的最大快乐指数
    return max(dp[1][0], dp[1][1])

# 示例输入
n = 6
happiness = [0, 10, 20, 30, 40, 50, 60]  # 假设编号从1开始，第0个元素为占位符
tree = {
    1: [2, 3],
    2: [4, 5],
    3: [6],
    4: [],
    5: [],
    6: []
}

# 计算最大快乐指数
print(max_happiness(n, happiness, tree))